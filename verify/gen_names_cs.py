"""名前の表(m0/Assets/Master/names_ja.json)から、Domain の C# ソース(NameTable.g.cs)を作る(09 §12.1 の MasterGen)。

使い方: python3 -I verify/gen_names_cs.py [出力先 .cs]
表の並びは名前の生成(NameGenerator。look_seed → 添字)に直結する。並びを変えると生成される名前が変わる(セーブの互換が切れる)ので、足すときは末尾に足す。
検査: かなは平仮名と長音だけ・同じ表記の重複なし・空でない・留学生の仮の名前の部品はカタカナだけ。
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "m0", "Assets", "Master", "names_ja.json")
DST = os.path.join(HERE, "..", "m0", "Assets", "Scripts", "Domain", "Text", "NameTable.g.cs")
HIRA = re.compile(r"^[ぁ-ゖー]+$")
KATA = re.compile(r"^[ァ-ヶー]+$")


def s(x):
    assert '"' not in x and "\\" not in x, x
    return '"' + x + '"'


def arr(items):
    return "new[] { " + ", ".join(s(i) for i in items) + " }"


def main():
    d = json.load(open(SRC, encoding="utf-8"))
    for key in ("family", "given"):
        seen = set()
        for e in d[key]:
            assert e["text"] and HIRA.match(e["kana"]), (key, e)
            assert e["text"] not in seen, (key, e["text"])
            seen.add(e["text"])
    for key in ("family_parts", "given_parts"):
        assert len(d["intl"][key]) >= 2
        for col in d["intl"][key]:
            assert col and len(set(col)) == len(col), (key, col)
            for p in col:
                assert KATA.match(p), (key, p)
    out = sys.argv[1] if len(sys.argv) > 1 else DST
    L = ["// <auto-generated> verify/gen_names_cs.py が m0/Assets/Master/names_ja.json から作った。手で編集しない。</auto-generated>",
         "namespace Ekiden.Domain.Text", "{",
         "    /// <summary>名前の表(names_ja.json)。選手の姓・名とそのかな。並びは名前の生成の添字に直結する(足すときは末尾に)。</summary>",
         "    public static class NameTableData", "    {",
         "        public static readonly string[] FamilyText = " + arr([e["text"] for e in d["family"]]) + ";",
         "        public static readonly string[] FamilyKana = " + arr([e["kana"] for e in d["family"]]) + ";",
         "        public static readonly string[] GivenText = " + arr([e["text"] for e in d["given"]]) + ";",
         "        public static readonly string[] GivenKana = " + arr([e["kana"] for e in d["given"]]) + ";",
         "        /// <summary>留学生の仮の名前の部品(列ごとに 1 つ引いてつなぐ。L-20 の国別の表ができるまで)。</summary>",
         "        public static readonly string[][] IntlFamilyParts = new[] { " + ", ".join(arr(c) for c in d["intl"]["family_parts"]) + " };",
         "        public static readonly string[][] IntlGivenParts = new[] { " + ", ".join(arr(c) for c in d["intl"]["given_parts"]) + " };",
         "    }", "}", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    print("姓 %d・名 %d・留学生の部品 %d 列 / %d 列: %s" % (len(d["family"]), len(d["given"]), len(d["intl"]["family_parts"]), len(d["intl"]["given_parts"]), os.path.abspath(out)))


if __name__ == "__main__":
    main()
