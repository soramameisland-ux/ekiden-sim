"""基準ペース pace50(d) = 176 + 6 ln(d/5) の『倍精度の値の表』を C# のソースとして出力する(09 §8.4 の MasterGen の代わり)。

使い方: python3 -I gen_master_pace50.py [出力先 .cs]
距離は有限の集合(区間・記録・予選会の距離)。実装ではこの表を引き、`log` を呼ばない(04 §2)。
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ref_model_04 as m4  # noqa: E402

EXTRA = [5.0, 10.0, 21.0975, 20.0, 8.0, 23.1, 21.3]      # PB の距離(5000m・10000m・ハーフ)・予選会・検算の距離


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "m0", "Assets", "Scripts", "Domain", "Race", "Pace50Table.g.cs")
    dists = sorted({d for secs in m4.COURSE.values() for d, _, _ in secs} | set(EXTRA))
    lines = ["// <auto-generated> verify/gen_master_pace50.py が出力した。直接編集しない。pace50(d) = 176 + 6 ln(d/5)(04 §2・09 §8.4)。</auto-generated>",
             "using System.Collections.Generic;", "", "namespace Ekiden.Domain.Race", "{", "    public static partial class Pace50", "    {",
             "        private static readonly Dictionary<double, double> Table = new Dictionary<double, double>", "        {"]
    for d in dists:
        lines.append(f"            {{ {d!r}, {m4.pace50(d)!r} }},")
    lines += ["        };", "    }", "}", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(dists)} 個の距離の表を出力: {os.path.abspath(out)}")


if __name__ == "__main__":
    main()
