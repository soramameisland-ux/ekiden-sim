"""M0 段階 6: events_06.py のイベントカタログから C# のカタログ(EventCatalog.g.cs)を作る。

使い方: python3 -I gen_events_cs.py [出力ファイル]
カタログの元データは events_06.py(仕様 06 §14 の表)。生成物は手で編集しない(テストが参照モデルとの一致を確かめる)。
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import events_06 as ev6  # noqa: E402

CAT = {"Team": "Team", "Management": "Management", "Individual": "Individual", "Race": "Race", "Hometown": "Hometown", "Graduation": "Graduation", "Awakening": "Awakening"}
SCOPE = {"team": "Team", "runner": "Runner", "pair": "Pair"}
TARGET = {"r": "R", "p": "P", "all": "All", "g1": "G1", "g2": "G2", "g3": "G3", "g4": "G4", "top10": "Top10", "same_pref": "SamePref", "same_group": "SameGroup",
          "far": "Far", "near": "Near", "overseas": "Overseas", "captain": "Captain", "team": "Team"}
MODKIND = {"E_mult": "EMult", "r_add": "RAdd", "inj_mult": "InjMult", "form_add": "FormAdd", "funds_year": "FundsYear", "scout_pts": "ScoutPts"}
SEL = {"top_bond": "TopBond", "top_p": "TopP", "top_men": "TopMen"}
SEV = {"Minor": "Minor", "Moderate": "Moderate", "Severe": "Severe"}


def s(x):
    return '"' + x.replace("\\", "\\\\").replace('"', '\\"') + '"'


def d(x):
    return repr(float(x))


def ints(v):
    return "null" if v is None else "new[] { " + ", ".join(str(i) for i in v) + " }"


def fx_cs(fx):
    op = fx["op"]
    p = d(fx["p"]) if fx.get("p") is not None else None
    t = "Target." + TARGET[fx["to"]] if fx.get("to") else None
    if op == "mot":
        return f"B.Mot({t}, {fx['d']}" + (f", {p}" if p else "") + ")"
    if op == "fat":
        return f"B.Fat({t}, {fx['d']}" + (f", {p}" if p else "") + ")"
    if op == "xp":
        return f"B.Xp({t}, {s(fx['stat'])}, {fx['xu']}" + (f", {p}" if p else "") + ")"
    if op == "bond":
        return f"B.Bond({fx['d']})"
    if op == "bondg":
        return f"B.Bondg({t}, {fx['d']})"
    if op == "inj":
        return f"B.Inj({t}, InjurySeverityKind.{SEV[fx['sev']]})"
    if op == "skill":
        return f"B.Skill({t}, {s(fx['id'])}" + (f", {p}" if p else "") + ")"
    if op == "funds":
        return f"B.Funds({fx['d']})"
    if op == "scout":
        return f"B.Scout({fx['d']})"
    if op == "guide":
        return f"B.Guide({fx['d']})"
    if op == "mod":
        return f"B.Mod(ModKind.{MODKIND[fx['kind']]}, {t}, {d(fx['value'])}, {fx['weeks']})"
    if op == "captain":
        return f"B.Captain(CaptainSelect.{SEL[fx['select']]})"
    if op == "bench":
        return "B.Bench()"
    if op == "entry":
        return "B.Entry()"
    if op == "ob_role":
        return f"B.ObRole(ObRole.{fx['role']}, {fx['weeks']})"
    raise ValueError(op)


def choice_cs(c):
    fx = "new[] { " + ", ".join(fx_cs(f) for f in c["fx"]) + " }" if c["fx"] else "null"
    return f"B.C({s(c['id'])}, {s(c['label'])}, {fx}" + (f", req: {s(c['req'])}" if c["req"] else "") + ")"


def event_cs(e):
    ch = ",\n                ".join(choice_cs(c) for c in e["choices"])
    args = [s(e["id"]), "EventCategory." + CAT[e["cat"]], s(e["name"]), "EventScope." + SCOPE[e["scope"]], s(e["cond"]), d(e["p"]),
            "new[]\n            {\n                " + ch + ",\n            }", "new[] { " + ", ".join(s(x) for x in e["default"]) + " }"]
    kw = []
    if e["months"] is not None:
        kw.append(f"months: {ints(e['months'])}")
    if e["weeks"] is not None:
        kw.append(f"weeks: {ints(e['weeks'])}")
    if e["phase"] != "normal":
        kw.append("phase: EventPhaseKind.Race")
    if e["cooldown"]:
        kw.append(f"cooldown: {e['cooldown']}")
    if e["once"]:
        kw.append("once: OnceKind." + e["once"].capitalize())
    if e["max_year"] is not None:
        kw.append(f"maxYear: {e['max_year']}")
    if e["priority"] != 50:
        kw.append(f"priority: {e['priority']}")
    if e["exempt"]:
        kw.append("exempt: true")
    if e.get("hint"):
        kw.append(f"hint: {s(e['hint'])}")
    return "            B.E(" + ", ".join(args + kw) + ")"


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "m0", "Assets", "Scripts", "Domain", "Events", "EventCatalog.g.cs")
    lines = ["// <auto-generated> verify/gen_events_cs.py が events_06.py から作った。手で編集しない。</auto-generated>",
             "using System.Collections.Generic;", "", "namespace Ekiden.Domain.Events", "{",
             "    /// <summary>06 §14 の初期イベント(手書き34件)と §9 の特殊能力(19件。覚醒イベントは 18 件)。</summary>",
             "    public static class EventCatalogData", "    {",
             "        public static EventCatalog Create()", "        {",
             "            var authored = new List<EventDef>", "            {"]
    lines.append(",\n".join(event_cs(e) for e in ev6.EVENTS) + ",")
    lines += ["            };", "            var skills = new List<SkillDef>", "            {"]
    for sid, name, rank, cond in ev6.SKILLS:
        lines.append(f"                new SkillDef({s(sid)}, {s(name)}, SkillRank.{rank}, {s(cond)}),")
    lines += ["            };", "            var exclusive = new List<KeyValuePair<string, string>>", "            {"]
    for a, b in ev6.EXCLUSIVE:
        lines.append(f"                new KeyValuePair<string, string>({s(a)}, {s(b)}),")
    lines += ["            };", "            return new EventCatalog(authored, skills, exclusive).Prepare();", "        }", "    }", "}", ""]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out, len(ev6.EVENTS), "events,", len(ev6.SKILLS), "skills")


if __name__ == "__main__":
    main()
